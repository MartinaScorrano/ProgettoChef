package it.univaq.model;
/**
 * Classe enumerativa Measurement utilizzata per indicare il tipo di unità di misura presa in considerazione in una ricetta per un certo ingrediente specifico;
 * 
 */
public enum Measurement {
    GRAMS,
    KILOGRAMS,
    OUNCES,
    POUND,
    MILLILITERS,
    LITERS,
    TEASPOON,
    TABLESPOON,
    CUP,
    CLOVE,
    PINCH,
    TO_TASTE;
    
}
